import assert from 'node:assert/strict';
import { loadEnvFile } from 'node:process';
loadEnvFile('.env.local');
const base = process.env.RSVP_TEST_ORIGIN || 'http://127.0.0.1:3100';
let cookie = '';
async function api(body, options = {}) {
 const response = await fetch(`${base}/api/rsvp`,{method:body?'POST':'GET',headers:{'Content-Type':'application/json',Origin:base,...(cookie?{Cookie:cookie}:{}),...options.headers},...(body?{body:JSON.stringify(body)}:{})});
 const nextCookie=response.headers.get('set-cookie');
 if(nextCookie)cookie=nextCookie.split(';')[0];
 return {status:response.status,body:await response.json()};
}
assert.equal((await api()).status,401);
assert.equal((await api({action:'lookup',mode:'name',query:'Alex Example'},{headers:{Origin:'https://unrelated.example'}})).status,403);
assert.equal((await api({action:'lookup',mode:'name',query:'%'})).status,400);
assert.equal((await api({action:'confirm',token:'forged'})).status,401);
const missing=await api({action:'lookup',mode:'name',query:'Nobody Notinvited'});
assert.equal(missing.status,200);assert.equal(missing.body.matches.length,0);
const name=await api({action:'lookup',mode:'name',query:'  Alex   Example  '});
assert.equal(name.status,200);assert.equal(name.body.matches.length,1);
const email=await api({action:'lookup',mode:'email',query:'alex@example.com'});
assert.equal(email.status,200);assert.deepEqual(email.body.matches[0].guestNames,['Alex Example','Sam Example']);
const confirmed=await api({action:'confirm',token:name.body.matches[0].token});
assert.equal(confirmed.status,200);assert.ok(cookie);
const household=confirmed.body.household;
assert.equal(household.events.length,2);
assert.equal(household.events.find(event=>event.name==='Test welcome party').guests.length,1);
assert.equal(JSON.stringify(household).includes('address_line'),false);
assert.equal((await api({action:'save',responses:[]})).status,400);
const answers=household.events.flatMap(event=>event.guests.map(guest=>({guestId:guest.id,eventId:event.id,attendance:guest.name==='Sam Example'?'declined':'attending'})));
const foreign=answers.map((answer,index)=>index===0?{...answer,guestId:'20000000-0000-4000-8000-000000000003'}:answer);
assert.equal((await api({action:'save',responses:foreign})).status,400);
assert.equal((await api({action:'save',responses:[answers[0],answers[0],answers[0]]})).status,400);
assert.equal((await api({action:'save',responses:answers})).status,200);
const reloaded=await api();assert.equal(reloaded.status,200);
assert.equal(reloaded.body.household.events.find(event=>event.name==='Test wedding').guests.find(guest=>guest.name==='Sam Example').attendance,'declined');
const updated=answers.map(answer=>({...answer,attendance:'attending'}));
assert.equal((await api({action:'save',responses:updated})).status,200);
assert.ok((await api()).body.household.events.every(event=>event.guests.every(guest=>guest.attendance==='attending')));
const headers={apikey:process.env.SUPABASE_SECRET_KEY,'Content-Type':'application/json'};
const dbBase=process.env.SUPABASE_URL+'/rest/v1';
const before=await (await fetch(`${dbBase}/rsvp_responses?select=guest_id,event_id,attendance&order=guest_id,event_id`,{headers})).text();
const rejected=await fetch(`${dbBase}/rpc/save_household_rsvp`,{method:'POST',headers,body:JSON.stringify({p_household_id:household.id,p_responses:foreign})});
assert.equal(rejected.ok,false);
const after=await (await fetch(`${dbBase}/rsvp_responses?select=guest_id,event_id,attendance&order=guest_id,event_id`,{headers})).text();
assert.equal(after,before,'Invalid database save must leave all answers unchanged');
cookie='';
const jordan=await api({action:'lookup',mode:'name',query:'Jordan Sample'});
const jordanSession=await api({action:'confirm',token:jordan.body.matches[0].token});
assert.equal(jordanSession.body.household.events.length,1);
assert.equal(jordanSession.body.household.events[0].guests.length,1);
assert.equal(jordanSession.body.household.events[0].guests[0].name,'Jordan Sample');
assert.equal((await api({action:'save',responses:updated})).status,400);
console.log('PASS: name/email lookup, confirmation, invited-only events, submit/reload/update, invalid/foreign/duplicate rejection, atomic database rejection, and household isolation.');
